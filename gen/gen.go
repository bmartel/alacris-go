// Package gen turns alacris component definitions into typed Go wrappers.
//
// The source of truth is the define() call itself:
//
//	define('user-card', {
//	  props: { name: 'anon', age: 0, tags: [] },
//	  setup({ name, age, tags }, host) { ... },
//	});
//
// becomes a UserCardProps struct and a UserCard function returning an
// *alacris.Element. The generator knows each prop's default, so a value equal
// to it is left off the rendered element.
//
// What define() cannot say (that an event carries a particular detail, that a
// number is really an integer, which slots exist) is read from a JSDoc block
// above the call. See the jsdoc.go file comment for the tags.
//
// A props object the scanner cannot read as literal data is an error, never a
// guess. When a component builds its props at runtime, write the component
// into a manifest file by hand and generate from that instead; Load accepts
// either.
package gen

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Load reads components from any mix of JavaScript files, directories and
// manifest files, and returns them as one sorted manifest.
func Load(paths ...string) (*Manifest, error) {
	if len(paths) == 0 {
		return nil, fmt.Errorf("gen: nothing to read")
	}

	m := &Manifest{Version: ManifestVersion}
	for _, p := range paths {
		info, err := os.Stat(p)
		if err != nil {
			return nil, err
		}

		switch {
		case info.IsDir():
			cs, err := ParseDir(p)
			if err != nil {
				return nil, err
			}
			m.Components = append(m.Components, cs...)

		case strings.EqualFold(filepath.Ext(p), ".json"):
			f, err := os.Open(p)
			if err != nil {
				return nil, err
			}
			loaded, err := ReadManifest(f)
			f.Close()
			if err != nil {
				return nil, fmt.Errorf("%s: %w", p, err)
			}
			m.Components = append(m.Components, loaded.Components...)

		default:
			cs, err := ParseFile(p)
			if err != nil {
				return nil, err
			}
			m.Components = append(m.Components, cs...)
		}
	}

	m.Sort()
	return m, nil
}

// WriteFiles writes generated files into dir, creating it if needed. Existing
// files are only rewritten when their contents change, so a generate step does
// not disturb build caches or file watchers for components that did not move.
func WriteFiles(dir string, files []File) (written []string, err error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	for _, f := range files {
		path := filepath.Join(dir, f.Name)
		if old, err := os.ReadFile(path); err == nil && string(old) == string(f.Source) {
			continue
		}
		if err := os.WriteFile(path, f.Source, 0o644); err != nil {
			return written, err
		}
		written = append(written, path)
	}
	return written, nil
}

// Stale lists generated files in dir that this run did not produce — the
// leftovers from a component that was renamed or deleted.
func Stale(dir string, files []File) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	current := map[string]bool{}
	for _, f := range files {
		current[f.Name] = true
	}

	var stale []string
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, "_gen.go") || current[name] {
			continue
		}
		// Only files this tool wrote are ever reported.
		body, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, err
		}
		if strings.HasPrefix(string(body), "// Code generated by alacris-go") {
			stale = append(stale, filepath.Join(dir, name))
		}
	}
	return stale, nil
}
