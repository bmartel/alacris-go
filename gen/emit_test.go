package gen

import (
	"strings"
	"testing"
)

func generate(t *testing.T, src string, opts Options) string {
	t.Helper()
	components, err := ParseSource("widgets.js", src)
	if err != nil {
		t.Fatalf("ParseSource: %v", err)
	}
	if opts.Package == "" {
		opts.Package = "ui"
	}
	files, err := Generate(&Manifest{Components: components}, opts)
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	var b strings.Builder
	for _, f := range files {
		b.WriteString("//// " + f.Name + "\n")
		b.Write(f.Source)
	}
	return b.String()
}

func mustContain(t *testing.T, got string, want ...string) {
	t.Helper()
	for _, w := range want {
		if !strings.Contains(got, w) {
			t.Errorf("missing:\n\t%s\nin:\n%s", w, got)
		}
	}
}

func TestGenerateProps(t *testing.T) {
	got := generate(t, `
define('user-card', {
  props: { name: 'anon', age: 0, step: 1, tags: [], config: {}, active: false },
  setup,
});`, Options{})

	mustContain(t, got,
		`const UserCardTag = "user-card"`,
		"type UserCardProps struct {",
		"func UserCard(p UserCardProps) *alacris.Element {",
		`e := alacris.E(UserCardTag)`,

		// A zero value means "unset", so it is left off entirely.
		`if p.Age != 0 {`,
		`e.Prop("age", p.Age)`,

		// With a non-zero default, matching it is also "unset": writing the
		// attribute out would say the same thing at more bytes.
		`if p.Name != "" && p.Name != "anon" {`,
		`if p.Step != 0 && p.Step != 1 {`,

		// JSON props are decided by length, not by comparison.
		`if len(p.Tags) > 0 {`,
		`if len(p.Config) > 0 {`,
	)

	gotNonEmpty := generate(t, `
define('role-card', {
  props: { roles: ['user'] },
  setup,
});`, Options{})
	mustContain(t, gotNonEmpty,
		`if p.Roles != nil {`,
		`e.Prop("roles", p.Roles)`,
	)
}

func TestGenerateBoolWithTrueDefaultIsAPointer(t *testing.T) {
	// A plain bool field could never mean "leave it alone" when the default is
	// true: Go's zero value is false, so the component's default would be
	// unreachable from Go.
	got := generate(t, `define('x-y', { props: { open: true, shut: false }, setup });`, Options{})

	mustContain(t, got,
		"Open *bool",
		"Shut bool",
		"if p.Open != nil {",
		`e.Prop("open", *p.Open)`,
		"if p.Shut {",
	)
}

func TestGeneratePointerMode(t *testing.T) {
	got := generate(t, `define('x-y', { props: { name: 'anon', age: 0 }, setup });`,
		Options{Optional: OptionalPointer})

	mustContain(t, got, "Name *string", "if p.Name != nil {", `e.Prop("name", *p.Name)`)
	// A default that already is the zero value needs no pointer to express.
	if strings.Contains(got, "Age *int") {
		t.Errorf("age should stay a plain int:\n%s", got)
	}
}

func TestGenerateEventsAndSlots(t *testing.T) {
	got := generate(t, `
/**
 * @fires greet {name: string, times: integer} - said hello
 * @fires reset - went back to the start
 * @slot title - the heading
 */
define('user-card', { props: { name: 'anon' }, setup });`, Options{})

	mustContain(t, got,
		`UserCardEventGreet = "greet"`,
		`UserCardEventReset = "reset"`,
		"type UserCardGreetDetail struct {",
		"Name  string `json:\"name\"`",
		"Times int    `json:\"times\"`",
		`UserCardSlotTitle = "title"`,
	)
	// An event with no declared detail gets a constant but no empty struct.
	if strings.Contains(got, "UserCardResetDetail") {
		t.Errorf("an event with no detail should not generate a detail type:\n%s", got)
	}
}

// A prop's JSDoc description is untrusted: it can come from a third-party
// component a project wraps with `generate`. A newline in it must never escape
// the doc comment and land as top-level Go, or wrapping a hostile component
// would inject code that runs at the consumer's build time.
func TestGenerateDoesNotLetDocCommentsInjectCode(t *testing.T) {
	got := generate(t, `
define('x-evil', {
  props: {
    /**
     * a friendly widget
     * } func pwned() { panic("injected") } var _ = struct{ x int
     */
    foo: [],
  },
  setup,
});`, Options{})

	// The payload survives, but only ever as comment text.
	mustContain(t, got, "// } func pwned()")
	for _, line := range strings.Split(got, "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "func pwned(") {
			t.Fatalf("injected func escaped the doc comment into top-level Go:\n%s", got)
		}
	}
}

func TestGenerateStripPrefix(t *testing.T) {
	got := generate(t, `define('ala-counter', { props: { start: 0 }, setup });`,
		Options{StripPrefix: "ala-"})

	mustContain(t, got, "func Counter(p CounterProps)", `const CounterTag = "ala-counter"`)
}

func TestGenerateSharedFile(t *testing.T) {
	got := generate(t, `
define('x-one', { setup });
define('x-two', { setup });`, Options{})

	mustContain(t, got,
		"//// alacris_gen.go",
		"var Tags = []string{",
		`"x-one",`,
		`"x-two",`,
		"Code generated by alacris-go. DO NOT EDIT.",
	)
}

func TestGenerateNamedGoType(t *testing.T) {
	got := generate(t, `
/**
 * @prop {go:money.Amount} price
 * @goimport money example.com/money
 */
define('x-price', { props: { price: {} }, setup });`, Options{})

	mustContain(t, got,
		`money "example.com/money"`,
		"Price money.Amount",
		// A named type has no operator to compare against, so the zero check
		// goes through the runtime helper.
		"if !alacris.IsZero(p.Price) {",
	)
}

func TestGenerateRejectsCollisions(t *testing.T) {
	_, err := Generate(&Manifest{Components: []Component{
		{Tag: "user-card", Source: "a.js:1"},
		{Tag: "user--card", Source: "b.js:1"},
	}}, Options{Package: "ui"})
	if err == nil || !strings.Contains(err.Error(), "goName") {
		t.Errorf("two tags generating one identifier should be an error, got %v", err)
	}

	// One component carries the project prefix and one does not; stripping it
	// makes them the same Go identifier.
	_, err = Generate(&Manifest{Components: []Component{
		{Tag: "ala-todo-item", Source: "a.js:1"},
		{Tag: "todo-item", Source: "b.js:1"},
	}}, Options{Package: "ui", StripPrefix: "ala-"})
	if err == nil || !strings.Contains(err.Error(), "strip") {
		t.Errorf("stripping a prefix into a collision should be an error, got %v", err)
	}
}

func TestGeneratedSourcePathsDoNotDependOnTheWorkingDirectory(t *testing.T) {
	// The same components generated from the repository root and from the
	// package directory have to produce the same bytes, or `alacris-go check`
	// reports a difference that is not one.
	components := []Component{{Tag: "x-y", Source: "web/components.js:1"}}

	fromRoot, err := Generate(&Manifest{Components: []Component{
		{Tag: "x-y", Source: "examples/todo/web/components.js:1"},
	}}, Options{Package: "ui", RelativeTo: "examples/todo/ui"})
	if err != nil {
		t.Fatal(err)
	}
	fromPackage, err := Generate(&Manifest{Components: components},
		Options{Package: "ui", RelativeTo: "ui"})
	if err != nil {
		t.Fatal(err)
	}

	if string(fromRoot[0].Source) != string(fromPackage[0].Source) {
		t.Errorf("output depends on where the generator ran:\n%s\n---\n%s",
			fromRoot[0].Source, fromPackage[0].Source)
	}
	if !strings.Contains(string(fromRoot[0].Source), "../web/components.js") {
		t.Errorf("the header should point at the source relative to the package:\n%s", fromRoot[0].Source)
	}
}

func TestGeneratedCodeIsStable(t *testing.T) {
	// Generation runs on every build in some setups; identical input has to
	// produce identical bytes or it churns file watchers and version control.
	src := `define('x-y', { props: { b: 1, a: 2, c: 3 }, setup });`
	first := generate(t, src, Options{})
	for i := 0; i < 3; i++ {
		if got := generate(t, src, Options{}); got != first {
			t.Fatal("generated output is not deterministic")
		}
	}
}
